/** Actual app, synthetic weather only: rendering, minimized controls and restoration. */
import assert from 'node:assert/strict';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { chromium } from 'playwright';
const dir = await mkdtemp(join(tmpdir(), 'office-weather-'));
process.env.BUILDING_DB = join(dir, 'test.sqlite'); delete process.env.T3_LOCAL_DATA;
const { createServer } = await import('vite');
const server = await createServer({ server: { host: 'localhost', port: 0, hmr: false }, logLevel: 'error' });
let browser;
try {
 await server.listen(); browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-webgl'] });
 const page = await browser.newPage({ viewport: { width: 1280, height: 800 } }), errors = [];
 page.on('pageerror', e => errors.push(e.message));
 await page.goto(server.resolvedUrls.local[0] + '?source=demo&agents=2&weather=rain&time=12:00&lang=en');
 await page.waitForFunction(() => window.__ready, {}, { timeout: 90000 });
 await page.evaluate(() => document.querySelector('.office-welcome')?.remove());
 await page.click('#hud [data-tab=likes]');
 await page.evaluate(() => { window.__originalHud = document.querySelector('#hud'); window.__originalPlayer = window.__player; });
 await page.click('.human-launcher');
 assert.ok(await page.locator('.human-panel').isVisible());
 await page.click('.office-building-launcher');
 await page.waitForFunction(() => window.__buildingView?.pending() === 0 && document.querySelectorAll('.building-world-labels button').length > 0);
 await page.waitForFunction(() => !window.__buildingView.moving());
 assert.equal(await page.locator('.building-world').getAttribute('data-weather'), 'rain');
 for (const s of ['#hud .deck', '#hud .clock', '.human-panel']) assert.equal(await page.locator(s).isVisible(), false, s + ' minimized');
 assert.equal(await page.locator('#hud').evaluate(e => e.inert), true);
 const inspect = () => page.evaluate(() => { const w = window.__buildingView.weather; return { rain: w.rain.visible, snow: w.snow.visible, drops: w.rain.geometry.drawRange.count, flakes: w.snow.geometry.drawRange.count, positions: Array.from(w.rain.geometry.attributes.position.array.slice(0, 12)) }; });
 const rainy = await inspect(); assert.ok(rainy.rain && !rainy.snow && rainy.drops > 0 && rainy.drops <= 1024);
 await page.waitForTimeout(200); assert.notDeepEqual((await inspect()).positions, rainy.positions, 'Rain falls');
 await mkdir('shots', { recursive: true }); await page.screenshot({ path: 'shots/building-weather-rain.png' });
 await page.getByRole('button', { name: 'Show controls', exact: true }).click();
 assert.ok(await page.locator('#hud .deck').isVisible()); assert.equal(await page.locator('.human-panel').isVisible(), false, 'Office people panel stays folded in building');
 assert.equal(await page.locator('#hud').evaluate(e => e.inert), false);
 await page.getByRole('button', { name: 'Hide controls', exact: true }).click();
 const weather = async (state, rain, snow) => {
  await page.evaluate(({ state, rain, snow }) => { window.__settings.set('weather', state); window.__weather.rain = rain; window.__weather.snow = snow; }, { state, rain, snow });
  await page.waitForFunction(state => document.querySelector('.building-world').dataset.weather === state, state);
  await page.waitForTimeout(100);
 };
 await weather('snow', 0, .7); const snowy = await inspect(); assert.ok(snowy.snow && !snowy.rain && snowy.flakes > 0 && snowy.flakes <= 512);
 await weather('clear', 0, 0); assert.ok(!(await inspect()).rain && !(await inspect()).snow);
 await weather('storm', 1, 0); assert.ok((await inspect()).rain);
 await page.emulateMedia({ reducedMotion: 'reduce' }); await page.waitForTimeout(150);
 const still = (await inspect()).positions; await page.waitForTimeout(200); assert.deepEqual((await inspect()).positions, still, 'Reduced motion freezes precipitation');
 await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(300);
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'No mobile overflow');
 await page.getByRole('button', { name: 'Show controls', exact: true }).click();
 await page.getByRole('button', { name: 'Hide controls', exact: true }).click();
 await page.evaluate(() => { const w = window.__buildingView.weather; window.__oldWeather = w; window.__disposed = 0; for (const o of [w.rain, w.snow]) for (const r of [o.geometry, o.material]) r.addEventListener('dispose', () => window.__disposed++); });
 await page.getByRole('button', { name: 'Back to office', exact: false }).click();
 assert.deepEqual(await page.evaluate(() => ({ disposed: window.__disposed, detached: window.__oldWeather.group.parent === null, hud: window.__originalHud === document.querySelector('#hud'), player: window.__originalPlayer === window.__player, inert: document.querySelector('#hud').inert, nestedInert: document.querySelector('#hud .deck header').inert })), { disposed: 4, detached: true, hud: true, player: true, inert: false, nestedInert: false });
 assert.ok(await page.locator('.human-panel').isVisible());
 await page.setViewportSize({ width: 1280, height: 800 }); await page.waitForTimeout(300);
 assert.ok(await page.locator('#hud .deck').isVisible());
 assert.ok(await page.locator('#hud [data-tab=likes]').evaluate(e => e.classList.contains('on')), 'Radio tab retained');
 assert.deepEqual(errors, []);
 console.log('PASS: live rain/snow/clear/storm, bounded buffers, moving/static reduced-motion precipitation, mobile controls, minimized panels, same HUD/player state and GPU disposal.');
} finally { await browser?.close(); await server.close(); await rm(dir, { recursive: true, force: true }); }
